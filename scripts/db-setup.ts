/**
 * One-time database setup. Run by the owner after installing PostgreSQL 16:
 *
 *   npm run db:setup                    (add -- --reset-passwords to rotate app passwords)
 *
 * Asks for the postgres superuser password (hidden, never stored), then creates the restricted
 * roles and the databases pump_prod (real data), pump_demo (demo data), pump_test (tests),
 * and writes generated passwords for the login roles into .env (git-ignored).
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { promptHidden } from "./lib/prompt";
import { provision } from "./lib/provision";

const newPassword = () => randomBytes(24).toString("base64url");

function readEnvFile(): Record<string, string> {
  const out: Record<string, string> = {};
  if (!existsSync(".env")) return out;
  for (const line of readFileSync(".env", "utf8").split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

async function main() {
  const reset = process.argv.includes("--reset-passwords");
  const env = readEnvFile();
  const keys = { pump_migrator: "DB_MIGRATOR_PASSWORD", pump_app: "DB_APP_PASSWORD", pump_backup: "DB_BACKUP_PASSWORD" } as const;
  const passwords: Record<string, string> = {};
  for (const [role, key] of Object.entries(keys)) {
    if (reset || !env[key]) {
      env[key] = newPassword();
      passwords[role] = env[key];
    }
  }
  env.DB_HOST ??= "127.0.0.1";
  env.DB_PORT ??= "5432";
  // Password from a file (installer handoff) or typed hidden. Never printed, never stored by this script.
  const pwFile = process.env.PG_SUPERPASS_FILE;
  const superPassword = pwFile
    ? readFileSync(pwFile, "utf8").trim().split(/\r?\n/).pop()!.trim()
    : await promptHidden("postgres superuser password: ");
  await provision({
    host: env.DB_HOST,
    port: Number(env.DB_PORT),
    superUser: "postgres",
    superPassword,
    databases: ["pump_prod", "pump_demo", "pump_test"],
    passwords,
  });
  env.DB_NAME ??= "pump_demo"; // DEMO until the go-live cut-over (decision D14)
  env.SESSION_SECRET ??= randomBytes(32).toString("base64url");
  writeFileSync(
    ".env",
    "# Generated by scripts/db-setup.ts. Never commit or share this file.\n" +
      Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") + "\n",
    "utf8",
  );
  console.log(`Done. Credentials written to .env. Active database: ${env.DB_NAME}`);
}

main().catch((e) => {
  console.error("Setup failed:", e instanceof Error ? e.message : e);
  process.exit(1);
});
